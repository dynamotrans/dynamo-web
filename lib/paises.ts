/** Los que van arriba del todo en los desplegables. */
export const PAISES_PRIMEROS = ['ES', 'PT', 'PL'];

/** [código ISO, nombre] — la forma que ya usaban los formularios. */
export const PAISES: [string, string][] = PAISES_MUNDO.map(([c, n]) => [c, n]);

// Prefijos que comparten varios países: el país que "representa" al prefijo
// (la bandera que se ve cuando solo se conoce el número).
const PRINCIPAL: Record<string, string> = {
  '+1': 'US', '+7': 'RU', '+44': 'GB', '+47': 'NO', '+61': 'AU', '+262': 'RE', '+290': 'SH',
  '+358': 'FI', '+590': 'GP', '+599': 'CW', '+672': 'NF', '+212': 'MA', '+500': 'FK', '+64': 'NZ',
  '+39': 'IT',
};

/** [prefijo, país] — un prefijo por fila, con su país principal. */
export const PREFIJOS: [string, string][] = (() => {
  const vistos = new Map<string, string>();
  for (const [c, n, d] of PAISES_MUNDO) {
    if (PRINCIPAL[d] ? PRINCIPAL[d] === c : !vistos.has(d)) vistos.set(d, n);
  }
  return [...vistos.entries()];
})();

/** País (ISO) que representa a un prefijo. */
export function paisDePrefijo(d: string): string {
  return PRINCIPAL[d] ?? PAISES_MUNDO.find(([, , p]) => p === d)?.[0] ?? '';
}

/** Bandera (emoji) a partir del código ISO. */
export function bandera(cc: string): string {
  if (!/^[A-Za-z]{2}$/.test(cc || '')) return '';
  return String.fromCodePoint(...[...cc.toUpperCase()].map((l) => 0x1f1a5 + l.charCodeAt(0)));
}

export const paisDe = (c: string) => PAISES_MUNDO.find(([k]) => k === c)?.[1] ?? c;
export const esPaisValido = (c: string) => PAISES_MUNDO.some(([k]) => k === c);

const PREF_POR_LARGO = PREFIJOS.map(([p]) => p).sort((a, b) => b.length - a.length);

export function partirTel(t: string): { pref: string; num: string } {
  const v = (t || '').replace(/\s/g, '');
  const p = PREF_POR_LARGO.find((k) => v.startsWith(k));
  return p ? { pref: p, num: v.slice(p.length) } : { pref: '+34', num: v.replace(/^\+/, '') };
}
export function telBonito(t: string) {
  if (!t) return '';
  const { pref, num: n } = partirTel(t);
  return `${pref} ${n.replace(/(\d{3})(?=\d)/g, '$1 ')}`.trim();
}
